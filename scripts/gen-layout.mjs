// Single source of truth for the shared memory layout between WASM (AssemblyScript) and TS.
// Run: node scripts/gen-layout.mjs  (done automatically by npm run build:wasm)
import { writeFileSync, mkdirSync } from 'node:fs';

const PARAMS = [
  // airframe
  'MASS_EMPTY', 'TANK_CAP_L', 'TANK_INIT_L', 'LIQ_DENS', 'N_MOTORS', 'COAX', 'ARM_LEN', 'PROP_D',
  'FMAX', 'TAU_MOTOR', 'KQ', 'YAW_AUTH', 'RG_XY', 'RG_Z', 'CDA_XY', 'CDA_Z', 'KH',
  'GEAR_W', 'GEAR_H', 'BODY_R', 'FM', 'ETA', 'AVIONICS_W', 'PUMP_W',
  // battery
  'BATT_S', 'BATT_MAH', 'BATT_R', 'BATT_CHEM', 'BATT_INIT_SOC',
  // flight controller
  'FC_PROFILE', 'MAX_TILT', 'MAX_YAWRATE', 'MAX_CLIMB', 'MAX_DESC', 'MAX_SPEED', 'LOIT_ACC',
  'RTL_ALT', 'LAND_SPEED', 'FLOW_LPM', 'MIN_SATS', 'HAS_RADAR', 'CRASH_VZ', 'LOW_BATT', 'CRIT_BATT',
  'RESP', // response multiplier for attitude gains
  // slosh
  'SLOSH_FRAC', 'SLOSH_FREQ', 'SLOSH_ZETA', 'TANK_Z',
  // environment
  'ELEV', 'TEMP', 'WIND_SPD', 'WIND_DIR', 'GUST', 'TURB', 'GPS_BASE_SATS', 'RTK', 'SEED',
  'HOME_X', 'HOME_Y', 'HOME_YAW',
  'FIELD_X0', 'FIELD_X1', 'FIELD_Y0', 'FIELD_Y1', 'CROP_H', // crop canopy: radar measures height above the crop
  'HOLD_ASSIST', // 1 = ALT HOLD / ATTI brakes and holds position when sticks are centred (beginner)
  'OBS_COUNT',
];
const OBS_MAX = 96, OBS_STRIDE = 8;

const INPUTS = [
  'ROLL', 'PITCH', 'YAW', 'THR', 'MODE', 'ARM_SW', 'ARM_SW_EN', 'SPRAY', 'RTL_SW', 'RC_OK',
  'FAIL_MOTOR', 'FAIL_GPS', 'COMPASS_ERR', 'WIND_SPD', 'WIND_DIR', 'GUST', 'TURB', 'KILL', 'FLOW',
  // AUTO mission guidance from the TS mission manager: fly the leg A→B at height Z (Z<0 = land), speed SPD
  'AUTO_ON', 'AUTO_AX', 'AUTO_AY', 'AUTO_BX', 'AUTO_BY', 'AUTO_Z', 'AUTO_SPD',
  'ARM_CMD', // ground-station arm request (rising edge), like 'slide to take off'
];

const OUTPUTS = [
  'T', 'X', 'Y', 'Z', 'VX', 'VY', 'VZ', 'QW', 'QX', 'QY', 'QZ', 'ROLL', 'PITCH', 'YAW', 'P', 'Q', 'R',
  'M0', 'M1', 'M2', 'M3', 'M4', 'M5', 'M6', 'M7',
  'BATT_V', 'BATT_I', 'BATT_SOC', 'BATT_MAH_USED', 'TANK_L', 'MASS',
  'WIND_X', 'WIND_Y', 'WIND_Z', 'SATS', 'HDOP', 'FIX', 'EST_X', 'EST_Y', 'BARO_ALT', 'RADAR_AGL',
  'MODE', 'ARMED', 'CRASHED', 'CRASH_CAUSE', 'AIRSPEED', 'GNDSPEED', 'VSPEED', 'THRUST', 'THR_OUT',
  'SPRAYING', 'ON_GROUND', 'HOME_DIST', 'WARN', 'SLOSH_X', 'SLOSH_Y', 'LANDED', 'HEADING',
  'TGT_ALT', 'POWER_W', 'FLIGHT_TIME',
  'EV_COUNT',
];
const EV_MAX = 32;

function block(names) { const o = {}; names.forEach((n, i) => (o[n] = i)); return o; }
const P = block(PARAMS), I = block(INPUTS), O = block(OUTPUTS);
const P_OBS = PARAMS.length, P_SIZE = P_OBS + OBS_MAX * OBS_STRIDE;
const O_EV = OUTPUTS.length, O_SIZE = O_EV + EV_MAX;

const hdr = '// GENERATED by scripts/gen-layout.mjs — do not edit.\n';
let as = hdr;
for (const [k, v] of Object.entries(P)) as += `export const P_${k}: i32 = ${v};\n`;
for (const [k, v] of Object.entries(I)) as += `export const I_${k}: i32 = ${v};\n`;
for (const [k, v] of Object.entries(O)) as += `export const O_${k}: i32 = ${v};\n`;
as += `export const P_OBS: i32 = ${P_OBS};\nexport const OBS_MAX: i32 = ${OBS_MAX};\nexport const OBS_STRIDE: i32 = ${OBS_STRIDE};\n`;
as += `export const P_SIZE: i32 = ${P_SIZE};\nexport const I_SIZE: i32 = ${INPUTS.length};\n`;
as += `export const O_EV: i32 = ${O_EV};\nexport const EV_MAX: i32 = ${EV_MAX};\nexport const O_SIZE: i32 = ${O_SIZE};\n`;

let ts = hdr;
ts += `export const P = ${JSON.stringify(P)} as const;\n`;
ts += `export const I = ${JSON.stringify(I)} as const;\n`;
ts += `export const O = ${JSON.stringify(O)} as const;\n`;
ts += `export const P_OBS = ${P_OBS}, OBS_MAX = ${OBS_MAX}, OBS_STRIDE = ${OBS_STRIDE}, P_SIZE = ${P_SIZE};\n`;
ts += `export const I_SIZE = ${INPUTS.length}, O_EV = ${O_EV}, EV_MAX = ${EV_MAX}, O_SIZE = ${O_SIZE};\n`;

mkdirSync('assembly', { recursive: true });
mkdirSync('src/sim', { recursive: true });
writeFileSync('assembly/layout.ts', as);
writeFileSync('src/sim/layout.ts', ts);
console.log(`layout: P=${P_SIZE} I=${INPUTS.length} O=${O_SIZE}`);
